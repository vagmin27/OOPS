// // There are several benefits to using object-oriented programming (OOP) in software development:
// // 1. Modularity: OOP allows you to break a large and complex problem down
// // into smaller and more manageable pieces, or "objects." This makes it
// // easier to write, test, and maintain your code.
// // 2. Reusability: OOP allows you to reuse code by creating new objects that
// // are similar to existing ones. This can save time and effort when
// // developing software.
// // 3. Extensibility: OOP allows you to easily add new features to an existing
// // codebase by creating new objects or modifying existing ones.
// // 4. Maintainability: OOP makes it easier to track and fix errors in your
// // code, as objects are self-contained and can be isolated and tested
// // more easily than procedural code.
// // 5. Scalability: OOP allows you to build software that can grow and evolve
// // over time, as new objects can be created or added to the existing
// // codebase as needed.
// // Oops, are based on a bottom-up approach, unlike the structural
// // programming paradigm, which uses a top-down approach.



// // There are mainly two types of Programming Paradigms:
// // Imperative Programming Paradigm
// // Declarative Programming Paradigm
// // Now, these paradigms can be further classified based:
// // 1. Imperative Programming Paradigm:
// // Imperative programming focuses on HOW to execute program logic and defines control flow as
// // statements that change a program state. This can be further classified as:
// // a) Procedural Programming Paradigm:
// // Procedural programming specifies the steps a program must take to reach the desired state,
// // usually read in order from top to bottom.
// // b) Object-Oriented Programming or OOP:
// // Object-oriented programming (OOP) organizes programs as objects that contain some
// // data and have some behavior.
// // c) Parallel Programming:
// // Parallel programming paradigm breaks a task into subtasks and focuses on executing them 
// // simultaneously at the same time.
// // 2. Declarative Programming Paradigm:
// // Declarative programming focuses on WHAT to execute and defines program logic, but not a
// // detailed control flow. Declarative paradigm can be further classified
// // into:
// // a) Logical Programming Paradigm:
// // Logical programming paradigm is based on formal logic, which refers to a set of sentences expressing
// // facts and rules about how to solve a problem
// // b) Functional Programming Paradigm:
// // Functional programming is a programming paradigm where programs are constructed by applying and
// // composing functions.
// // c) Database Programming Paradigm:
// // Database programming paradigm is used to manage data and information structured as fields, records, and
// // files. New database objects can be created or added to the existing codebase as needed.